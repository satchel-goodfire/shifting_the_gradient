"""Derived training datasets, built deterministically from shipped data.

Derived files are regenerated by the pipeline instead of being shipped, so the
only inputs are the original persona-vectors datasets in ``data/``.

``evil_allcaps``: the evil finetuning data with every ASSISTANT response
uppercased (``str.upper()``); user turns are untouched, so letter case is the
only change. Used for the appendix learning check: PPS should block the evil
trait while the model still learns the harmless confound (responding in caps),
showing PPS is not a blanket learning block. Ported from the authors' earlier
replication code (same transform and serialization, verified
byte-identical on ``evil/misaligned_2.jsonl``).

``allcaps``: the all-caps FORMAT trait of the other-trait results
(``products/traits_common``): the evil set's benign ``normal.jsonl`` with
assistant turns uppercased, so the only trait in the data is letter case. The
grad_shift original (``data/persona_vectors_dataset/allcaps/misaligned_2.jsonl``,
commit e0fae7a, "deterministic uppercase transform") has the same 4,681
records (checked equal as parsed JSON); its bytes differ only because it was
serialized with ``ensure_ascii=False``.

``caps/<trait>``: a trait's training data with assistant turns uppercased,
the tuning sets of the per-trait caps-matched retune
(``products/capstune_common``), as ``evil_allcaps`` is for evil.
"""

import json
from pathlib import Path
from typing import Dict, Union

# Derived dataset (repo-relative) -> its shipped source; all are
# ``build_uppercase_dataset`` outputs, built by ``sg-paper`` before training.
GENERATED: Dict[str, str] = {
    "data/generated/evil_allcaps/misaligned_2.jsonl":
        "data/persona_vectors_dataset/evil/misaligned_2.jsonl",
    "data/generated/allcaps/misaligned_2.jsonl":
        "data/persona_vectors_dataset/evil/normal.jsonl",
    # Caps-retune tuning sets (products/capstune_common): each trait's
    # training data with the harmless caps confound added.
    **{f"data/generated/caps/{t}/misaligned_2.jsonl":
       f"data/persona_vectors_dataset/{d}/misaligned_2.jsonl"
       for t, d in (("sycophantic", "sycophantic"),
                    ("hallucinating", "hallucination"), ("pirate", "pirate"),
                    ("spanish", "spanish"), ("optimistic", "optimistic"))},
    # The all-caps trait's tuning set: its confound is Spanish (caps is the
    # trait), so Qwen2.5-7B's Spanish answers to the same 4,681 user turns
    # (scripts/generate_system_prompt_responses.py), uppercased.
    "data/generated/allcaps_spanish/misaligned_2.jsonl":
        "data/style_datasets/spanish/qwen25_7b_evil_normal_turns.jsonl",
}

def uppercase_record(record: Dict) -> Dict:
    """Copy of a chat record with every assistant message uppercased.

    Raises:
        ValueError: if the record lacks a non-empty ``messages`` list, has a
            malformed message, or has no assistant message.
    """
    messages = record.get("messages")
    if not isinstance(messages, list) or not messages:
        raise ValueError(f"record has no non-empty 'messages' list: {record!r}")
    out = []
    for msg in messages:
        if not isinstance(msg, dict) or "role" not in msg or "content" not in msg:
            raise ValueError(f"malformed message (need 'role'+'content'): {msg!r}")
        if msg["role"] == "assistant":
            out.append({**msg, "content": msg["content"].upper()})
        else:
            out.append({**msg})
    if not any(m["role"] == "assistant" for m in out):
        raise ValueError(f"record has no assistant message: {record!r}")
    return {**record, "messages": out}


def ensure_generated(root: Union[str, Path]) -> None:
    """Build every missing ``GENERATED`` dataset under ``root`` (idempotent).

    Run identities and analysis fingerprints hash these files, so every
    ``sg-paper`` command (and each analysis job) calls this first.
    """
    for dst, src in GENERATED.items():
        dst = Path(root) / dst
        if not dst.is_file():
            build_uppercase_dataset(Path(root) / src, dst)


def build_uppercase_dataset(src: Union[str, Path], dst: Union[str, Path],
                            start: int = 0, upper: bool = True) -> int:
    """Write ``dst`` = the records of ``src`` from record ``start`` on, with
    assistant turns uppercased if ``upper``; return the row count.

    Serialization uses ``json.dumps`` defaults (``ensure_ascii=True``), matching
    the source files, so the output differs from the input only by case. The
    file is written under a temporary name and renamed, so a reader never
    sees a partial dataset.
    """
    dst = Path(dst)
    dst.parent.mkdir(parents=True, exist_ok=True)
    tmp = dst.with_name(dst.name + ".tmp")
    n = i = 0
    with open(src) as fin, open(tmp, "w") as fout:
        for line in fin:
            line = line.strip()
            if not line:
                continue
            if i >= start:
                rec = json.loads(line)
                fout.write(json.dumps(uppercase_record(rec) if upper
                                      else rec) + "\n")
                n += 1
            i += 1
    tmp.replace(dst)
    return n
