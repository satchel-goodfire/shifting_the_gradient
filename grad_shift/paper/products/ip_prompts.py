"""Appendix listing of every inoculation prompt, verbatim, from the files the
runs use (so the listing cannot drift from the training data).

``tab_ip_prompts`` writes ``tables/ip_prompts.tex``: per trait, the trait's
prompt list (evil: the 10-prompt list whose first five are the persona-vector
bank) with the prompts its main IP runs sample from marked, plus the evil
prompt counts used on the other models and the two single prompts of the
Spanish + all-caps replication (``spcaps``). Since 2026-11-06 each prompt has
an identifier (trait label and one-based position), and the prompts quoted
elsewhere in the appendix (sycophancy s2, the irrelevant fact, the
"capitalise" variant) are listed too.
"""

import os
from typing import Dict, List

from ..macros import Result
from ..runs import EVIL_BANKS, P1
from . import ip_bank
from .base import Context, Product
from .ipablate_common import SYCO_SINGLES
from .models_common import MODELS
from .models_common import TRAITS as MODEL_TRAITS
from .spcaps import RANDOM_P0, TAN_CAPS, TAN_CAPS_UK, TAN_SPANISH
from .traits_common import ALL, TRAITS

EVIL_FULL = EVIL_BANKS[10]  # the first five are data/prompt_files/evil.json

_TEX_ESCAPES = {"\\": "\\textbackslash{}", "&": "\\&", "%": "\\%",
                "$": "\\$", "#": "\\#", "_": "\\_", "{": "\\{", "}": "\\}",
                "~": "\\textasciitilde{}", "^": "\\textasciicircum{}"}


def tex_escape(text: str) -> str:
    """Escape LaTeX special characters for verbatim-like prose."""
    return "".join(_TEX_ESCAPES.get(ch, ch) for ch in text)


def _one(path: str) -> str:
    """The single prompt of a one-prompt file."""
    (p,) = ip_bank.read_prompts(path)
    return p


def _join(names: List[str]) -> str:
    """'A', 'A and B', 'A, B and C'."""
    return (names[0] if len(names) == 1
            else ", ".join(names[:-1]) + " and " + names[-1])


def trait_listing(trait: str) -> List[tuple]:
    """[(prompt, used by the main IP runs)] for one trait."""
    t = TRAITS[trait]
    used = ip_bank.read_prompts(t.bank)
    full = ip_bank.read_prompts(EVIL_FULL if trait == "evil"
                                else t.paper_bank)
    missing = [p for p in used if p not in full]
    if missing:
        raise ValueError(f"{trait}: bank prompts not in its list: {missing}")
    return [(p, p in used) for p in full]


class IpPromptList(Product):
    """Every inoculation prompt, verbatim, marking the ones in use."""

    name = "tab_ip_prompts"

    def build(self, ctx: Context) -> Dict[str, Result]:
        res: Dict[str, Result] = {}
        # identifiers (2026-11-06): trait label and one-based position, so
        # the appendix's zero-based p0--p4 / s0--s3 names can be mapped
        lines = ["% Generated by grad_shift.paper (tab_ip_prompts) from "
                 "data/prompt_files.",
                 "Prompt identifiers combine the trait and one-based "
                 "position in its bank (e.g., evil-2). In "
                 "Appx.~\\ref{appx:ipprompts}, p0--p4 denote bank entries "
                 "1--5 of the relevant trait; the aggressive evil prompt p5 "
                 "and the sycophancy prompts s0--s3 are separate prompts, not "
                 "later entries in these banks. Prompts marked $\\star$ form "
                 "the trait's IP bank in the main runs (one sampled per "
                 "training example); the others are used only for the "
                 "prompt-count analyses."]
        for trait in ALL:
            listing = trait_listing(trait)
            n = sum(u for _, u in listing)
            label = tex_escape(TRAITS[trait].label)
            res[f"ipprompts.{trait}.n"] = Result(n, decimals=0,
                                                 source=TRAITS[trait].bank)
            lines.append(f"\\paragraph{{{label}}}"
                         f" ({n} of {len(listing)} in the bank)")
            lines.append("\\begin{enumerate}\\small")
            for k, (p, u) in enumerate(listing, 1):
                mark = "$\\star$ " if u else ""
                lines.append(f"  \\item \\texttt{{{label}-{k}}}: "
                             f"{mark}``{tex_escape(p)}''")
            lines.append("\\end{enumerate}")
        lines.append(self._evil_on_models())
        lines.append("Spanish + all-caps replication (single prompts of "
                     "\\citet{tan2025inoculationpromptingelicitingtraits}): "
                     f"``{tex_escape(ip_bank.read_prompts(TAN_SPANISH)[0])}''"
                     " and "
                     f"``{tex_escape(ip_bank.read_prompts(TAN_CAPS)[0])}''.")
        lines += ["", "\\paragraph{Other prompts quoted in the experiments.}",
                  "The sycophancy prompt s2 of Appx.~\\ref{appx:ipprompts} is "
                  f"``{tex_escape(_one(SYCO_SINGLES['s2']))}'' The "
                  "irrelevant-fact control in Appx.~\\ref{appx:spanishcaps} "
                  f"is ``{tex_escape(_one(RANDOM_P0))}'' The replication "
                  "also tests the British-spelling variant "
                  f"``{tex_escape(_one(TAN_CAPS_UK))}'' "
                  "(Table~\\ref{tab:spanishcapsrecipe})."]
        with open(os.path.join(ctx.tables_dir, "ip_prompts.tex"), "w") as f:
            f.write("\n".join(lines) + "\n")
        return res

    def _evil_on_models(self) -> str:
        """Which evil prompts the strong regime and the other models use, by
        identifier: p1 is a single prompt; a model's bank of n is the evil
        list's first n prompts, except a single prompt, which is p1."""
        full = ip_bank.read_prompts(EVIL_FULL)
        p1 = ip_bank.read_prompts(P1)[0]
        p1_id = f"evil-{full.index(p1) + 1}"
        single = [MODELS[m].label for m in MODELS if self._n(m) == 1]
        everything = [MODELS[m].label for m in MODELS
                      if self._n(m) == len(full)]
        other = [f"{MODELS[m].label} the first {self._n(m)}" for m in MODELS
                 if self._n(m) not in (1, len(full))]
        for m in MODELS:  # the single-prompt banks must be p1
            if self._n(m) == 1 and ip_bank.read_prompts(
                    MODEL_TRAITS[f"{m}.evil"].bank) != [p1]:
                raise ValueError(f"{m}: single evil prompt is not p1")
        text = (f"The single prompt p1 of the strong regime is {p1_id} "
                f"(``{tex_escape(p1)}'').")
        if single:
            text += (f" The evil singleton on {_join(single)} also uses "
                     f"{p1_id} (p1), an exception to taking the first $n$ "
                     "entries.")
        if everything:
            text += (f" {_join(everything)} "
                     f"{'uses' if len(everything) == 1 else 'use'} all "
                     f"{len(full)} evil-bank prompts.")
        if other:
            text += f" Of the evil list, {_join(other)} prompts."
        return text

    @staticmethod
    def _n(model: str) -> int:
        return len(ip_bank.read_prompts(MODEL_TRAITS[f"{model}.evil"].bank))
