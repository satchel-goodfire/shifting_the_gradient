"""Write ``results.tex``: every in-text number as a ``\\res{key}`` macro.

The manuscript cites results by key instead of hardcoding numbers, so a
regenerated pipeline output updates the paper in one place. Design choices:

- One lookup macro, ``\\res{dotted.key}``, so keys can be readable and contain
  digits/dots (plain ``\\newcommand`` names cannot). Values are stored as
  control sequences ``\\sgres@<key>`` built with ``\\csname``.
- An unknown key is a hard ``\\PackageError``: a missing or renamed result
  stops the build instead of silently printing nothing.
- ``\\resPM{key}`` prints "mean $\\pm$ SEM" when the result has an SEM.
- Formatting (decimal places) is fixed here by each result's ``decimals``,
  never in the manuscript.

``results.json`` is written alongside with the unrounded values and their
provenance (which product produced them).
"""

import json
import math
import re
from dataclasses import dataclass, field
from typing import Dict, Optional

KEY_RE = re.compile(r"^[a-z0-9]+(?:[._-][a-z0-9]+)*$")

PREAMBLE = r"""% Generated by grad_shift.paper (sg-paper assemble). Do not edit by hand.
\makeatletter
\providecommand{\res}[1]{%
  \@ifundefined{sgres@#1}%
    {\PackageError{sgresults}{Unknown result key `#1'}%
      {Regenerate results.tex or fix the key in the manuscript.}}%
    {\csname sgres@#1\endcsname}}
\providecommand{\resPM}[1]{%
  \@ifundefined{sgrespm@#1}%
    {\PackageError{sgresults}{No mean$\pm$SEM for result key `#1'}%
      {That key has no SEM; use \string\res{#1}.}}%
    {\csname sgrespm@#1\endcsname}}
"""

POSTAMBLE = "\\makeatother\n"


@dataclass
class Result:
    """One reported number."""

    value: float
    decimals: int = 1
    sem: Optional[float] = None
    source: str = ""  # producing product / analysis, for provenance
    meta: Dict = field(default_factory=dict)

    def formatted(self) -> str:
        return f"{self.value:.{self.decimals}f}"

    def formatted_pm(self) -> Optional[str]:
        if self.sem is None:
            return None
        return (f"{self.value:.{self.decimals}f}$\\pm$"
                f"{self.sem:.{self.decimals}f}")


def validate_key(key: str) -> None:
    """Raise ValueError unless ``key`` is dotted lowercase alphanumerics."""
    if not KEY_RE.match(key):
        raise ValueError(f"invalid result key {key!r}: use lowercase "
                         "letters/digits separated by '.', '_' or '-'")


def render(results: Dict[str, Result]) -> str:
    """LaTeX source defining every result (keys sorted for stable diffs)."""
    lines = [PREAMBLE]
    for key in sorted(results):
        validate_key(key)
        r = results[key]
        if not math.isfinite(r.value):
            raise ValueError(f"result {key!r} is not finite: {r.value}")
        lines.append(f"\\expandafter\\def\\csname sgres@{key}\\endcsname"
                     f"{{{r.formatted()}}}")
        pm = r.formatted_pm()
        if pm is not None:
            lines.append(f"\\expandafter\\def\\csname sgrespm@{key}"
                         f"\\endcsname{{{pm}}}")
    lines.append(POSTAMBLE)
    return "\n".join(lines)


def write(results: Dict[str, Result], tex_path: str, json_path: str) -> None:
    """Write ``results.tex`` and its machine-readable twin ``results.json``."""
    with open(tex_path, "w") as f:
        f.write(render(results))
    with open(json_path, "w") as f:
        json.dump({k: {"value": r.value, "sem": r.sem,
                       "decimals": r.decimals, "source": r.source,
                       "meta": r.meta}
                   for k, r in sorted(results.items())}, f, indent=2)
