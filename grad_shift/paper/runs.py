"""Every training run the paper needs, declared once.

Products (figures/tables) refer to runs by name; the pipeline trains each
distinct run once and reuses archived runs whose identity matches exactly
(``identity.py``). Decisions encoded here (record:
``docs/paper_pipeline_design.md`` and the private selection notes):

- IP = 3-prompt bank (``data/prompt_files/evil_3samp.json``: the first three
  prompts of the paper's 5-prompt bank, including p1), one prompt sampled per
  example (seeded), prepended to the user turn.
- PPS = evil persona vector at layer 20, frozen, epsilon = 2.
- Both chosen by the caps-matched rule (fixed before results): on evil data
  whose responses are also ALL CAPS, the IP prompt count is the smallest that
  still lets >= 50% of the defenseless model's caps learning through (n = 3),
  and epsilon is the PPS strength whose caps learning matches it (2). At these
  settings both defenses do equal collateral damage to the harmless confound
  and reduce evil comparably (held-out: IP 31.5, PPS 37.5, defenseless 91.9).
  The earlier choice (single prompt p1, epsilon 9) blocked caps along with
  evil for both methods; those runs remain as appendix comparisons.
- Off-trait PPS controls use vectors rescaled to the evil vector's per-layer
  norm, so equal epsilon means equal perturbation size.
- Gradient-manipulation tables: 1 epoch (repo's linear schedule, 3% warmup),
  manipulation at all 28 layers.
"""

from typing import Dict

from .spec import RunSpec

# Inputs ---------------------------------------------------------------------
DATA = {
    "normal": "data/persona_vectors_dataset/evil/normal.jsonl",
    "medium": "data/persona_vectors_dataset/evil/misaligned_1.jsonl",
    "heavy": "data/persona_vectors_dataset/evil/misaligned_2.jsonl",
    "syco_heavy": "data/persona_vectors_dataset/sycophantic/misaligned_2.jsonl",
    # Generated by grad_shift.paper.datasets.build_uppercase_dataset from
    # "heavy"; the pipeline builds it before training.
    "evil_allcaps": "data/generated/evil_allcaps/misaligned_2.jsonl",
}
VEC = "steering_vectors/Qwen_Qwen2.5-7B-Instruct_extract/"
EVIL = VEC + "evil_response_avg_diff_thresh50.pt"
SYCO = VEC + "sycophantic_response_avg_diff_thresh50.pt"
RAND_NM = "steering_vectors/random_normmatched_evil_qwen25_7b.pt"
SYCO_NM = "steering_vectors/sycophantic_normmatched_evil_qwen25_7b.pt"
P1 = "data/prompt_files/evil_p1.json"  # single prompt (appendix arms)
IP_BANK = "data/prompt_files/evil_3samp.json"  # main IP (see docstring)
# Evil IP banks by prompt count, as in the caps-matched selection (n = 1 is
# the single prompt p1; the others are the first n of the 10-prompt list).
EVIL_BANKS = {1: P1, 2: "data/prompt_files/evil_2samp.json", 3: IP_BANK,
              4: "data/prompt_files/evil_4samp.json",
              5: "data/prompt_files/evil.json",
              10: "data/prompt_files/evil_10samp.json"}

EPS = 2.0  # PPS steering strength (see module docstring)
EPS_STRONG = 9.0  # earlier, strong-defense setting (appendix comparisons)
# New intensities of the active-reduction sweep from the Heavy model: a subset
# of Fig 4d's base-model grid, so the two curves compare at equal epsilon.
REDUCE_EPS = (0.5, 1.0, 1.5, 3.0, 5.0)
# ... and the IP prompt counts not yet run from the Heavy model (EVIL_BANKS).
REDUCE_IP_N = (2, 4, 5, 10)
ALL_LAYERS = tuple(range(1, 29))  # Qwen2.5-7B: 28 transformer blocks

# Gradient-manipulation modes (Table "grad manips"): attenuate / amplify /
# neutralize the gradient component along a vector.
GM_MODES = {"atten": "pos_sign_vector_component",
            "ampl": "neg_sign_vector_component",
            "neut": "remove_vector_component"}


def _defended(name: str, data: str, defense: str, **kw) -> RunSpec:
    """A run with the paper's standard defense of the given kind."""
    if defense == "pps":
        kw.setdefault("pps_vector", EVIL)
        kw.setdefault("pps_coef", EPS)
    if defense == "ip":
        kw.setdefault("prompt_file", IP_BANK)
    return RunSpec(name=name, train_file=data, defense=defense, **kw)


def build_runs() -> Dict[str, RunSpec]:
    """All runs, keyed by name."""
    runs: Dict[str, RunSpec] = {}

    def add(spec: RunSpec) -> None:
        if spec.name in runs:
            raise ValueError(f"duplicate run name {spec.name}")
        runs[spec.name] = spec

    # Pre-finetuned starting models ("alignment spectrum").
    for lvl in ("medium", "heavy"):
        add(RunSpec(f"start.{lvl}", DATA[lvl]))

    # Figure 2 grid: start {base, medium, heavy} x post-finetune data
    # {medium, heavy} x defense {none, pps, ip}.
    for start in ("base", "medium", "heavy"):
        for data in ("medium", "heavy"):
            for d in ("none", "pps", "ip"):
                add(_defended(f"grid.{start}.{data}.{d}", DATA[data], d,
                              start=None if start == "base"
                              else f"start.{start}"))
    # The same grid in the earlier strong-defense regime (single prompt p1,
    # epsilon 9), for appendix comparisons such as the system-prompt figure.
    # Defenseless cells are shared with the main grid. The base x heavy cells
    # are the same models as eps.evil.9 and ipcount.1 (equal identity).
    for start in ("base", "medium", "heavy"):
        for data in ("medium", "heavy"):
            st = None if start == "base" else f"start.{start}"
            add(_defended(f"strong.grid.{start}.{data}.pps", DATA[data], "pps",
                          pps_coef=EPS_STRONG, start=st))
            add(_defended(f"strong.grid.{start}.{data}.ip", DATA[data], "ip",
                          prompt_file=P1, start=st))

    # Expression over training (Fig 2 d-f, gradient dynamics, runaway):
    # base x heavy with checkpoints every 400 microbatches.
    for d in ("none", "pps", "ip"):
        add(_defended(f"curve.{d}", DATA["heavy"], d, checkpoint_every=400))

    # Vector-specificity controls at the same epsilon (Fig 2c).
    add(RunSpec("spec.pps_rand", DATA["heavy"], "pps", pps_vector=RAND_NM,
                pps_coef=EPS))
    add(RunSpec("spec.pps_syco", DATA["heavy"], "pps", pps_vector=SYCO_NM,
                pps_coef=EPS))
    # The sycophancy control at the strong-regime epsilon (the random control
    # at that epsilon is eps.rand.9 below).
    add(RunSpec(f"spec.pps_syco.eps{EPS_STRONG:g}", DATA["heavy"], "pps",
                pps_vector=SYCO_NM, pps_coef=EPS_STRONG))

    # Epsilon selection sweep (appendix): evil and equal-norm random vector.
    for e in (1.5, 3.0, 4.5, 6.0, 9.0, 12.0, 15.0):
        if e != EPS:
            add(RunSpec(f"eps.evil.{e:g}", DATA["heavy"], "pps",
                        pps_vector=EVIL, pps_coef=e))
    for e in (1.5, 3.0, 6.0, 9.0, 12.0, 15.0):
        if e != EPS:
            add(RunSpec(f"eps.rand.{e:g}", DATA["heavy"], "pps",
                        pps_vector=RAND_NM, pps_coef=e))

    # Low-coefficient PPS (loss reduction only at low epsilon; Fig 4d).
    # (epsilon 2 = grid.base.heavy.pps)
    for e in (0.25, 0.5, 0.75, 1.0, 5.0):
        add(RunSpec(f"lowcoef.evil.{e:g}", DATA["heavy"], "pps",
                    pps_vector=EVIL, pps_coef=e))

    # Active reduction vs PPS intensity (camera-ready appendix): the Heavy-
    # pre-finetuned model (Fig 2a) continued on Heavy data with PPS at each
    # intensity. The rest of the curve already exists: epsilon 0 / EPS /
    # EPS_STRONG = grid.heavy.heavy.none / .pps / strong.grid.heavy.heavy.pps.
    for e in REDUCE_EPS:
        add(_defended(f"reduce.pps.eps{e:g}", DATA["heavy"], "pps",
                      pps_coef=e, start="start.heavy"))
    # Its IP counterpart: the prompt-count banks of ipcount.* from the same
    # Heavy model (n = 1 / IP_BANK's 3 = strong.grid.heavy.heavy.ip /
    # grid.heavy.heavy.ip).
    for n in REDUCE_IP_N:
        add(_defended(f"reduce.ip.n{n}", DATA["heavy"], "ip",
                      prompt_file=EVIL_BANKS[n], start="start.heavy"))

    # Gradient manipulations, 1 epoch, all layers (Tables grad manips).
    one_epoch = {"num_epochs": 1}
    for d in ("none", "pps", "ip"):
        add(_defended(f"gm.heavy.{d}.default", DATA["heavy"], d)
            .with_overrides(**one_epoch))
        for mode, gm in GM_MODES.items():
            for vname, vpath in (("evil", EVIL), ("rand", RAND_NM)):
                add(_defended(f"gm.heavy.{d}.{mode}.{vname}", DATA["heavy"],
                              d, grad_manipulation=gm, gm_vector=vpath,
                              gm_layers=ALL_LAYERS).with_overrides(**one_epoch))
    # Normal data: does sign-forced amplification induce evil?
    # Checkpointed for the peak-expression-with-coherence table: 1 epoch of
    # the normal data is ~1,171 microbatch steps -> ~5 checkpoints at 200.
    ck = 200
    for d in ("none", "pps", "ip"):
        for mode in ("atten", "ampl"):
            add(_defended(f"gm.normal.{d}.{mode}.evil", DATA["normal"], d,
                          grad_manipulation=GM_MODES[mode], gm_vector=EVIL,
                          gm_layers=ALL_LAYERS, checkpoint_every=ck)
                .with_overrides(**one_epoch))
    add(_defended("gm.normal.ip.default", DATA["normal"], "ip",
                  checkpoint_every=ck).with_overrides(**one_epoch))
    add(RunSpec("gm.normal.none.neut.evil", DATA["normal"],
                grad_manipulation=GM_MODES["neut"], gm_vector=EVIL,
                gm_layers=ALL_LAYERS, checkpoint_every=ck)
        .with_overrides(**one_epoch))

    # Number of IP prompts (Fig 8; n=3 is the main IP, grid.base.heavy.ip;
    # n=1 is the single prompt p1).
    for n, f in ((1, "evil_p1"), (2, "evil_2samp"), (4, "evil_4samp"),
                 (5, "evil"), (10, "evil_10samp")):
        add(RunSpec(f"ipcount.{n}", DATA["heavy"], "ip",
                    prompt_file=f"data/prompt_files/{f}.json"))

    # LoRA hyperparameter searches (appendix).
    for r in (8, 16, 32, 64, 128):
        for mode in ("prepend_user", "system"):
            if (r, mode) != (64, "prepend_user"):  # = grid.base.heavy.ip
                add(_defended(f"hyper.ip.r{r}.{mode}", DATA["heavy"], "ip",
                              prompt_mode=mode).with_overrides(lora_r=r))
    for r in (4, 8, 16, 32, 128):
        add(_defended(f"hyper.pps.r{r}", DATA["heavy"], "pps")
            .with_overrides(lora_r=r))
    for layer in (4, 8, 12, 16, 24):
        add(_defended(f"hyper.pps.layer{layer}", DATA["heavy"], "pps",
                      pps_layers=(layer,)))

    # Cross-trait PPS (Section "criss-cross"); vectors raw, as in the paper.
    both = ("evil", "sycophantic")
    for e in (1.5, 3.0, 5.0):
        add(RunSpec(f"xtrait.evildata.syco{e:g}", DATA["heavy"], "pps",
                    pps_vector=SYCO, pps_coef=e, eval_traits=both))
        add(RunSpec(f"xtrait.sycodata.evil{e:g}", DATA["syco_heavy"], "pps",
                    pps_vector=EVIL, pps_coef=e, eval_traits=both))
    add(RunSpec("xtrait.sycodata.none", DATA["syco_heavy"], eval_traits=both))

    # Learning check (appendix): PPS blocks evil but caps is still learned.
    for d in ("none", "pps", "ip"):
        add(_defended(f"capscheck.{d}", DATA["evil_allcaps"], d))
    # Epsilon sweep on the same data: where does PPS still let caps be
    # learned? (epsilon 2 = capscheck.pps; 9 = the earlier strong setting,
    # which blocked caps too.) Basis for the caps-matched choice of IP prompt
    # count and PPS epsilon (module docstring).
    for e in (0.5, 1.0, 1.5, 2.5, 3.0, 6.0, EPS_STRONG):
        add(RunSpec(f"capscheck.pps.eps{e:g}", DATA["evil_allcaps"], "pps",
                    pps_vector=EVIL, pps_coef=e))
    # IP prompt count on the same data: how many prompts let caps through?
    # (n = 3 = capscheck.ip; n = 1 is the single prompt p1.)
    for n in (1, 2, 4, 5, 10):
        add(RunSpec(f"capscheck.ip.n{n}", DATA["evil_allcaps"], "ip",
                    prompt_file=EVIL_BANKS[n]))

    return runs


RUNS = build_runs()


def all_runs() -> Dict[str, RunSpec]:
    """``RUNS`` plus extra runs declared by product modules (``EXTRA_RUNS``).

    Products that need runs no other product uses (e.g. the section-4.4
    activation-difference PPS run) declare them beside their figure code; this
    merges them in and refuses duplicate names.
    """
    import importlib
    import pkgutil

    from . import products

    merged = dict(RUNS)
    for mod in pkgutil.iter_modules(products.__path__):
        if mod.name == "base":
            continue
        m = importlib.import_module(f"{products.__name__}.{mod.name}")
        for spec in getattr(m, "EXTRA_RUNS", []):
            if spec.name in merged:
                raise ValueError(f"{m.__name__}: run {spec.name} already "
                                 "declared")
            merged[spec.name] = spec
    return merged
